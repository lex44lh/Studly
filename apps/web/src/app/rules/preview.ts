export function legalPreviewEnabled() {
  return process.env.NODE_ENV === "development" && process.env.STUDLY_LEGAL_PREVIEW === "1";
}

export function getLegalPreviewSections(slug: string) {
  if (!legalPreviewEnabled() || !Object.hasOwn(drafts, slug)) return null;
  return drafts[slug];
}
